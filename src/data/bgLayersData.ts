/**
 * Computes the intensity-based scale factor for star flares/sprites.
 * Scales smoothly from 0.5 (50% size) at intensity = 0.0 to 1.0 (100% size) at max intensity (0.15).
 */
export const getStarFlareIntensityScale = (
  intensity: number,
  maxIntensity: number = 0.15
): number => {
  const safeIntensity = Number.isFinite(intensity) ? intensity : 0;
  const safeMax = Number.isFinite(maxIntensity) && maxIntensity > 0 ? maxIntensity : 0.15;
  const clamped = Math.max(0, Math.min(safeMax, safeIntensity));
  const progress = clamped / safeMax;
  return 0.5 + 0.5 * progress;
};

